def _norm_word(w: Dict[str, str]) -> Dict[str, str]:
    """统一字段：word / cn / phonetic / grade，兼容新旧数据。"""
    if "phonetic" in w:
        return w
    ph = w.get("us") or w.get("uk") or ""
    return {
        "word": w.get("word", ""),
        "cn": w.get("cn", ""),
        "phonetic": f"/{ph}/" if ph else "",
        "grade": w.get("grade", ""),
    }


ENGLISH_WORDS = [_norm_word(w) for w in ENGLISH_WORDS]
_ENG_BY_WORD = {w["word"].lower(): w for w in ENGLISH_WORDS}
_ENG_BY_CN: Dict[str, Dict[str, str]] = {}
for _w in ENGLISH_WORDS:
    _ENG_BY_CN.setdefault(_w["cn"], _w)


def find_word(query: str) -> Optional[Dict[str, str]]:
    q = (query or "").strip().lower()
    if not q:
        return None
    if q in _ENG_BY_WORD:
        return _ENG_BY_WORD[q]
    if q in _ENG_BY_CN:
        return _ENG_BY_CN[q]
    # 模糊：包含
    for w in ENGLISH_WORDS:
        if q in w["word"].lower() or q in w["cn"]:
            return w
    return None


def random_word() -> Dict[str, str]:
    return random.choice(ENGLISH_WORDS)


