def find_story(query: str) -> Optional[Dict[str, str]]:
    """按标题查故事：先精确包含，再模糊（去书名号、按两字片段）。"""
    q = (query or "").strip().strip("《》<>\"'")
    if not q:
        return None
    for s in STORIES:
        if q == s["title"]:
            return s
    for s in STORIES:
        if q in s["title"] or s["title"] in q:
            return s
    # 两字片段模糊要求标题至少一半字面重合，否则「不存在的故事」会误中别的故事
    if len(q) >= 2:
        for s in STORIES:
            hits = sum(1 for i in range(len(q) - 1) if q[i : i + 2] in s["title"])
            if hits and hits * 2 >= len(q) - 1:
                return s
    return None


def search_stories(query: str, limit: int = 3) -> List[Dict[str, str]]:
    """按标题模糊搜索多篇，用于给用户列候选。"""
    q = (query or "").strip().strip("《》<>\"'")
    if not q:
        return []
    hits: List[Dict[str, str]] = []
    for s in STORIES:
        if q in s["title"] or (len(q) >= 2 and any(q[i : i + 2] in s["title"] for i in range(len(q) - 1))):
            hits.append(s)
        if len(hits) >= limit:
            break
    return hits
