def pinyin_of(text: str) -> List[Tuple[str, str]]:
    """返回 [(字, 带声调拼音)]，逐字。"""
    from pypinyin import Style, pinyin

    text = (text or "").strip()
    if not text:
        return []
    # heteronym=True 拿多音字全部读音，但展示取第一个（最常见）
    py = pinyin(text, style=Style.TONE, heteronym=False)
    out: List[Tuple[str, str]] = []
    for ch, p in zip(text, py):
        out.append((ch, p[0] if p else ""))
    return out


def lookup_char(ch: str) -> Dict[str, Any]:
    """查一个字的拼音、组词、多音提示。"""
    from pypinyin import Style, pinyin

    py = pinyin(ch, style=Style.TONE, heteronym=True)
    readings = list(dict.fromkeys(py[0])) if py and py[0] else []
    words = WORDS.get(ch, [])
    return {
        "char": ch,
        "readings": readings,
        "words": words,
        "hint": POLYPHONE_HINT.get(ch, ""),
    }


# ---------------- 口算 ----------------

_math_state: Dict[str, Dict[str, Any]] = {}


def _make_question(level: int) -> Tuple[str, float]:
    """按难度生成一道口算题，返回 (题目, 答案)。"""
    level = max(1, min(int(level or 1), 4))
    if level == 1:  # 20 以内加减
        a = random.randint(1, 15)
        b = random.randint(1, 15)
        if random.random() < 0.5:
            return f"{a} + {b}", a + b
        a, b = max(a, b), min(a, b)
        return f"{a} - {b}", a - b
    if level == 2:  # 100 以内加减
        a = random.randint(10, 90)
        b = random.randint(1, 60)
        if random.random() < 0.5:
            return f"{a} + {b}", a + b
        a, b = max(a, b), min(a, b)
        return f"{a} - {b}", a - b
    if level == 3:  # 乘法口诀
        a = random.randint(2, 9)
        b = random.randint(2, 9)
        return f"{a} × {b}", a * b
    # level 4：两位数乘一位数 / 简单除法
    if random.random() < 0.5:
        a = random.randint(11, 30)
        b = random.randint(2, 9)
        return f"{a} × {b}", a * b
    b = random.randint(2, 9)
    ans = random.randint(2, 9)
    return f"{b * ans} ÷ {b}", ans


def new_math_question(key: str, level: int = 1) -> Dict[str, Any]:
    q, a = _make_question(level)
    _math_state[key] = {"q": q, "a": a, "t": time.time()}
    return {"question": q, "level": max(1, min(int(level or 1), 4))}


def check_math_answer(key: str, answer: str) -> Dict[str, Any]:
    st = _math_state.get(key)
    if not st:
        return {"has_question": False}
    raw = (answer or "").strip()
    try:
        num = float(raw)
    except (TypeError, ValueError):
        return {"has_question": True, "correct": None, "question": st["q"], "expected": st["a"]}
    ok = abs(num - float(st["a"])) < 1e-6
    # 答对就清掉，答错保留题让孩子再试
    if ok:
        _math_state.pop(key, None)
    return {"has_question": True, "correct": ok, "question": st["q"], "expected": st["a"]}


